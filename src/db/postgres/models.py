import uuid
from datetime import datetime

from sqlalchemy import ForeignKey, Text, func
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column

from src.db.postgres.init_db import Base
from src.enums import Platform, ProcessingStatus


class UserPostgres(Base):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    email: Mapped[str] = mapped_column(unique=True)
    hashed_password: Mapped[str]


class PostPostgres(Base):
    __tablename__ = "posts"

    id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    url: Mapped[str] = mapped_column(unique=True)
    platform: Mapped[Platform]
    status: Mapped[ProcessingStatus] = mapped_column(default=ProcessingStatus.PENDING)
    user_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("users.id"),
    )
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class TaskPostgres(Base):
    """One processing batch (`/process/all` or a retry); its posts live in `task_posts`."""

    __tablename__ = "tasks"

    id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    # The request's `log_id` (server-generated by `get_log_id()`, echoed as X-Request-ID).
    request_id: Mapped[str] = mapped_column(index=True)
    user_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("users.id"),
        index=True,
    )
    success_count: Mapped[int] = mapped_column(default=0, server_default="0")
    failed_count: Mapped[int] = mapped_column(default=0, server_default="0")
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class TaskPostPostgres(Base):
    """A post's outcome in one task; a post retried in several tasks has one row per task."""

    __tablename__ = "task_posts"

    task_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("tasks.id", ondelete="CASCADE"),
        primary_key=True,
    )
    post_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("posts.id", ondelete="CASCADE"),
        primary_key=True,
        index=True,
    )
    status: Mapped[ProcessingStatus] = mapped_column(default=ProcessingStatus.IN_PROCESS)
    # `PipelineStage` value where the post failed; None unless `status` is FAILED.
    stage: Mapped[str | None]
    error: Mapped[str | None] = mapped_column(Text)


class ScraperStatusPostgres(Base):
    """One row per platform: did its last scraper request get through (upserted by LinkScraper)."""

    __tablename__ = "scraper_statuses"

    id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    platform: Mapped[Platform] = mapped_column(unique=True)
    # FAILED only when the platform refused us (`ScraperStatusError`); post-level errors are SUCCESS.
    last_request_status: Mapped[ProcessingStatus]
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now())
